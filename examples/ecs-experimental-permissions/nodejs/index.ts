import * as path from "node:path";
import * as aws from "@pulumi/aws";
import * as awsx from "@pulumi/awsx";
import * as pulumi from "@pulumi/pulumi";
import * as awsxNext from "@pulumi/awsx-next";

const vpc = new awsx.ec2.Vpc("permissions", {
  numberOfAvailabilityZones: 1,
  subnetSpecs: [{ type: awsx.ec2.SubnetType.Public }],
  natGateways: { strategy: awsx.ec2.NatGatewayStrategy.None },
});
const securityGroup = new aws.ec2.SecurityGroup("permissions", {
  vpcId: vpc.vpcId,
  ingress: [],
  egress: [{ protocol: "tcp", fromPort: 443, toPort: 443, cidrBlocks: ["0.0.0.0/0"] }],
});
const cluster = new aws.ecs.Cluster("permissions");

const repository = new awsx.ecr.Repository("permissions", { forceDelete: true });
const image = new awsx.ecr.Image("app", {
  repositoryUrl: repository.url,
  context: path.join(__dirname),
  platform: "linux/amd64",
});

const bucket = new aws.s3.Bucket("environment", { forceDestroy: true });
const environmentFile = new aws.s3.BucketObjectv2("environment", {
  bucket: bucket.id,
  key: "startup.env",
  content: "ENV_FILE_VALUE=environment-file-ok\n",
  contentType: "text/plain",
});

// Both secret sources use a customer-managed key, exercising AWSX's KMS key lookups and grants.
const key = new aws.kms.Key("secrets", { deletionWindowInDays: 7 });
const secret = new aws.secretsmanager.Secret("injected", {
  kmsKeyId: key.arn,
  recoveryWindowInDays: 0,
});
const version = new aws.secretsmanager.SecretVersion("injected", {
  secretId: secret.id,
  secretString: pulumi.secret(JSON.stringify({ value: "secret-injection-ok" })),
});
const parameter = new aws.ssm.Parameter("injected", {
  type: "SecureString",
  keyId: key.arn,
  value: pulumi.secret("ssm-injection-ok"),
});

// No extra policies: ECS must pull the private image, decrypt/inject the secrets, load the
// environment file, and send logs using only the execution-role permissions generated by AWSX.
const task = new awsxNext.FargateTaskDefinitionV2(
  "startup",
  {
    cpuUnits: 256,
    memoryMiB: 512,
    containers: {
      app: {
        image: image.imageUri,
        environment: { SUCCESS_MARKER: "AWSX_PERMISSION_OK:startup" },
        secrets: {
          SECRETS_MANAGER_VALUE: { secretsManager: { secretArn: secret.arn, jsonKey: "value" } },
          PINNED_SECRET_VALUE: {
            secretsManager: {
              secretArn: secret.arn,
              jsonKey: "value",
              versionId: version.versionId,
            },
          },
          SSM_VALUE: { ssmParameterArn: parameter.arn },
        },
        environmentFiles: [{ bucketArn: bucket.arn, key: environmentFile.key }],
      },
    },
  },
  { dependsOn: [version, environmentFile] },
);

new aws.ecs.Service("startup", {
  cluster: cluster.arn,
  taskDefinition: task.taskDefinitionArn,
  desiredCount: 1,
  launchType: "FARGATE",
  platformVersion: "1.4.0",
  networkConfiguration: {
    subnets: vpc.publicSubnetIds,
    securityGroups: [securityGroup.id],
    assignPublicIp: true,
  },
  deploymentCircuitBreaker: { enable: true, rollback: false },
  waitForSteadyState: true,
});

export const logGroupName = task.logGroup.apply((group) => group!.name);
